const { execSync } = require('child_process');

try {
  execSync('pnpm install --config.confirmModulesPurge=false', { stdio: 'inherit', shell: true, cwd: __dirname });
  console.log('Installed Settings Sync node modules.');
} catch (err) {
  console.error('Failed to install Settings Sync node modules:', err && err.message);
  process.exit(err && typeof err.status === 'number' ? err.status : 1);
}
